from bert_score import score as bertscore

def eval_with_bertscore(candidate: str, reference: str):
    P, R, F1 = bertscore(
        [candidate],
        [reference],
        lang="en",
        verbose=False
    )
    return {
        "P": float(P[0]),
        "R": float(R[0]),
        "F1": float(F1[0])
    }

bertscore_led = eval_with_bertscore(led_summary, reference_summary)
